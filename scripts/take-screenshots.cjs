// 説明書（docs/manual.md）用のスクリーンショットを撮り直す（開発用）
// 使い方：npm run build → npx vite preview --port 4173 を起動した状態で
//         node scripts/take-screenshots.cjs
// Playwright（Chromium）が必要。初期サンプルデータ・1366x768 で撮影する。
const { chromium } = require('playwright')
const path = require('node:path')

const URL = 'http://localhost:4173'
const D = path.join(__dirname, '..', 'docs', 'images')
const shot = (p, name, opts = {}) => p.screenshot({ path: path.join(D, name), ...opts })

;(async () => {
  const b = await chromium.launch()
  const p = await b.newPage({ viewport: { width: 1366, height: 768 } })
  p.on('dialog', (d) => d.accept())
  const modal = p.locator('.modal')
  const cancel = () => modal.locator('button', { hasText: 'キャンセル' }).click()
  const rowCell = (name, n) => p.locator('tr.am', { has: p.locator('.row-name', { hasText: name }) }).locator('td').nth(n)

  await p.goto(URL)
  await shot(p, 'login.png')
  await p.fill('input >> nth=0', 'admin')
  await p.fill('input[type=password]', 'password')
  await p.click('button[type=submit]')
  await p.waitForTimeout(300)
  await shot(p, 'home.png')

  // 予定表
  await p.goto(`${URL}/#schedule`)
  await p.waitForSelector('.job')
  await shot(p, 'schedule-week.png')
  await p.click('.seg >> text=月')
  await p.waitForTimeout(200)
  await shot(p, 'schedule-month.png')
  await p.click('.seg >> text=週')
  await p.click('text=＋ 案件・休暇登録')
  await modal.locator('select', { has: p.locator('option[value=regular]') }).selectOption('regular')
  await shot(p, 'job-new.png')
  await cancel()
  await p.locator('.toolbar input[type=date]').fill(new Date().toISOString().slice(0, 8) + '12')
  await p.waitForTimeout(200)
  await p.locator('.job', { hasText: '小林' }).first().click()
  await shot(p, 'job-edit-multi.png')
  await cancel()
  await p.click('text=今日')
  await p.waitForTimeout(200)
  await p.locator('.memo').first().click()
  await shot(p, 'memo.png')
  await cancel()
  await p.click('text=📋 メモ一覧')
  await shot(p, 'memo-list.png')
  await p.locator('.modal-head button').click()
  await rowCell('鈴木', 1).click({ position: { x: 5, y: 5 } })
  await p.locator('.reg-tabs button', { hasText: '通常休暇' }).click()
  await shot(p, 'leave.png')
  await cancel()
  await p.click('text=🔍 検索')
  await p.locator('.search-panel input').first().fill('市川')
  await shot(p, 'search.png')

  // ドライバー・請求先
  await p.goto(`${URL}/#drivers`)
  await p.waitForTimeout(300)
  await p.locator('.order-list').first().scrollIntoViewIfNeeded()
  await shot(p, 'driver-order.png')
  await p.goto(`${URL}/#clients`)
  await p.waitForTimeout(200)
  await shot(p, 'clients.png')

  // 請求・支払
  await p.goto(`${URL}/#billing`)
  await p.waitForSelector('table.ledger')
  await shot(p, 'billing.png')
  await p.locator('.tabs button', { hasText: '単価マスタ' }).click()
  await shot(p, 'billing-rates.png')
  await p.locator('.tabs button', { hasText: '帳票' }).click()
  await p.locator('.card', { hasText: '請求書' }).locator('tr', { hasText: 'A物流' }).locator('button').click()
  await p.waitForSelector('.doc-sheet')
  await shot(p, 'invoice-edit.png')
  await p.locator('.doc-toolbar select').selectOption('送付済み')
  await p.click('text=← 閉じる')
  await shot(p, 'billing-docs.png')
  // 印刷イメージ（A4幅）
  await p.locator('.card', { hasText: '請求書' }).locator('tr', { hasText: 'A物流' }).locator('button').click()
  await p.waitForSelector('.doc-sheet')
  await p.setViewportSize({ width: 794, height: 1123 })
  await p.emulateMedia({ media: 'print' })
  await shot(p, 'invoice-print.png')
  await p.emulateMedia({ media: 'screen' })
  await p.setViewportSize({ width: 1366, height: 768 })
  await p.click('text=← 閉じる')

  await p.goto(`${URL}/#vehicles`)
  await p.waitForTimeout(300)
  await shot(p, 'vehicles.png')
  await b.close()
  console.log('docs/images を更新しました')
})()
